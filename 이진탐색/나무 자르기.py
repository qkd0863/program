import sys

# 입력 속도 향상
input = sys.stdin.readline

# n = 나무 개수
# m = 가져가야 하는 나무 길이
n, m = map(int, input().split())

# 나무 높이들 입력
trees = list(map(int, input().split()))

# 이분 탐색 범위
# 최소 높이 = 0
# 최대 높이 = 가장 높은 나무
start = 0
end = max(trees)

# 정답 저장 변수
answer = 0

# 이분 탐색 시작
while start <= end:

    # 현재 절단기 높이
    mid = (start + end) // 2

    # mid 높이로 잘랐을 때 얻는 나무 총합
    total = 0

    for tree in trees:

        # 나무가 절단기 높이보다 클 때만 잘림
        if tree > mid:

            # 잘린 부분 길이 추가
            total += tree - mid

    # 필요한 나무 길이 이상 얻을 수 있는 경우
    if total >= m:

        # 현재 높이는 가능하므로 저장
        answer = mid

        # 더 높은 높이도 가능한지 탐색
        start = mid + 1

    # 나무 길이가 부족한 경우
    else:

        # 절단기 높이를 낮춰야 함
        end = mid - 1

# 가능한 최대 높이 출력
print(answer)




